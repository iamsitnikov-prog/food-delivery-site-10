const TONE: Record<string, { cls: string; icon: string }> = {
  in: { cls: "text-brand", icon: "TrendingUp" },
  out: { cls: "text-[#ff6b6b]", icon: "TrendingDown" },
  flag: { cls: "text-[#ff6b6b]", icon: "TriangleAlert" },
  neutral: { cls: "text-cream-muted", icon: "Info" },
};

const ReportAnatomy = () => {
  const [tab, setTab] = useState(DOCS[0].key);
  const [open, setOpen] = useState<string | null>(DOCS[0].lines[0].label);
  const doc = DOCS.find((d) => d.key === tab)!;

  return (
    <div>
      <div className="flex flex-wrap gap-2">
        {DOCS.map((d) => (
          <button
            key={d.key}
            type="button"
            aria-pressed={tab === d.key}
            onClick={() => {
              setTab(d.key);
              setOpen(d.lines[0].label);
            }}
            className={`rounded-xl px-4 py-2.5 text-[0.9em] font-medium transition-colors ${
              tab === d.key
                ? "bg-foreground text-background"
                : "border border-foreground/15 text-muted-foreground hover:border-foreground/40"
            }`}
          >
            {d.tab}
          </button>
        ))}
      </div>

      <div className="mt-6 rounded-[32px] bg-surface p-6 text-cream md:p-10">
        <div className="flex flex-wrap items-baseline justify-between gap-3">
          <h3 className="font-display text-[1.5em] font-semibold tracking-[-0.02em]">
            {doc.title}
          </h3>
          <span className="rounded-lg bg-cream/[0.08] px-3 py-1.5 text-[0.8em] text-cream-muted">
            {doc.when}
          </span>
        </div>
        <p className="mt-1.5 font-mono text-[0.8em] text-cream-muted">{doc.file}</p>
        <p className="mt-4 max-w-[760px] leading-relaxed text-cream-muted">{doc.lead}</p>

        <p className="mt-6 text-[0.85em] text-cream-muted">
          Нажмите на строку, чтобы понять, что она значит
        </p>

        <div className="mt-3 space-y-2">
          {doc.lines.map((l) => {
            const isOpen = open === l.label;
            const tone = TONE[l.tone || "neutral"];
            return (
              <div
                key={l.label}
                className={`rounded-2xl transition-colors ${
                  isOpen ? "bg-cream/[0.1]" : "bg-cream/[0.05] hover:bg-cream/[0.08]"
                }`}
              >
                <button
                  type="button"
                  onClick={() => setOpen(isOpen ? null : l.label)}
                  aria-expanded={isOpen}
                  className="flex w-full items-center justify-between gap-4 p-4 text-left"
                >
                  <span className="flex min-w-0 items-center gap-2.5">
                    <Icon name={tone.icon} size={16} className={`shrink-0 ${tone.cls}`} />
                    <span className="truncate text-[0.95em] font-medium">{l.label}</span>
                  </span>
                  <span className="flex shrink-0 items-center gap-2.5">
                    <span className={`font-display text-[1.05em] font-semibold ${tone.cls}`}>
                      {l.value}
                    </span>
                    <Icon
                      name="ChevronDown"
                      size={16}
                      className={`text-cream-muted transition-transform ${isOpen ? "rotate-180" : ""}`}
                    />
                  </span>
                </button>
                {isOpen && (
                  <div className="border-t border-cream/12 px-4 pb-4 pt-3.5">
                    <p className="text-[0.92em] leading-snug">
                      <span className="text-brand">Что это. </span>
                      {l.what}
                    </p>
                    <p className="mt-2.5 text-[0.92em] leading-snug text-cream-muted">
                      <span className="text-cream">Почему важно. </span>
                      {l.why}
                    </p>
                    {l.action && (
                      <p className="mt-3 flex items-start gap-2 rounded-xl bg-brand/15 p-3 text-[0.9em] leading-snug">
                        <Icon name="ArrowRight" size={15} className="mt-0.5 shrink-0 text-brand" />
                        <span>{l.action}</span>
                      </p>
                    )}
                  </div>
                )}
              </div>
            );
          })}
        </div>

        <p className="mt-7 rounded-2xl bg-cream/[0.06] p-5 text-[0.95em] leading-snug">
          <span className="text-brand">Итог. </span>
          {doc.footer}
        </p>
      </div>
    </div>
  );
};

export default ReportAnatomy;
